"""Storage interface. Row values are plain dicts shaped like the Postgres rows; function results mirror the SQL functions in
db/migrations/0002_job_functions.sql (``{"ok": True, ...}`` or ``{"error": "<code>", ...}``).

Authorisation is NOT done here: callers resolve the tenant first (membership for users, token scope for runtimes) and pass explicit
workspace/runtime ids. The SQL functions re-check those ids against the rows, so a bug in a route cannot cross tenants silently.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any

Row = dict[str, Any]


class Store(ABC):
    # ---- tenancy
    @abstractmethod
    def create_workspace(self, user_id: str, name: str, slug: str) -> Row: ...   # {ok, workspace, project} | {error: slug_taken|workspace_limit}
    @abstractmethod
    def list_workspaces(self, user_id: str) -> list[Row]: ...
    @abstractmethod
    def get_role(self, user_id: str, workspace_id: str) -> str | None: ...
    @abstractmethod
    def create_project(self, workspace_id: str, name: str, user_id: str) -> Row: ...
    @abstractmethod
    def list_projects(self, workspace_id: str) -> list[Row]: ...
    @abstractmethod
    def get_project(self, project_id: str) -> Row | None: ...

    # ---- runtimes / credentials
    @abstractmethod
    def create_runtime(self, workspace_id: str, project_id: str, name: str, is_mock: bool, user_id: str) -> Row: ...
    @abstractmethod
    def get_runtime(self, runtime_id: str) -> Row | None: ...
    @abstractmethod
    def list_runtimes(self, project_id: str) -> list[Row]: ...
    @abstractmethod
    def add_credential(self, runtime: Row, prefix: str, secret_hash: str, expires_at: datetime, user_id: str, rotated_from: str | None = None) -> Row: ...
    @abstractmethod
    def get_credential_by_prefix(self, prefix: str) -> Row | None: ...
    @abstractmethod
    def revoke_credentials(self, runtime_id: str) -> int: ...
    @abstractmethod
    def revoke_credential(self, credential_id: str) -> None: ...
    @abstractmethod
    def list_credentials(self, runtime_id: str) -> list[Row]: ...
    @abstractmethod
    def touch_credential(self, credential_id: str) -> None: ...
    @abstractmethod
    def disable_runtime(self, runtime_id: str) -> None: ...
    @abstractmethod
    def register_runtime(self, runtime_id: str, info: Row) -> str: ...      # returns the new run id
    @abstractmethod
    def heartbeat(self, runtime_id: str) -> datetime | None: ...

    # ---- chat
    @abstractmethod
    def create_conversation(self, workspace_id: str, project_id: str, user_id: str, title: str | None, runtime_id: str | None) -> Row: ...
    @abstractmethod
    def get_conversation(self, conversation_id: str) -> Row | None: ...
    @abstractmethod
    def list_conversations(self, project_id: str, limit: int = 50) -> list[Row]: ...
    @abstractmethod
    def list_messages(self, conversation_id: str, limit: int = 200) -> list[Row]: ...

    # ---- jobs (mirror enigma_* SQL functions)
    @abstractmethod
    def submit_job(self, workspace_id: str, conversation_id: str, runtime_id: str, user_id: str, idem: str, content: str, params: Row, char_budget: int) -> Row: ...
    @abstractmethod
    def claim_job(self, runtime_id: str, owner: str, lease_seconds: int) -> Row | None: ...
    @abstractmethod
    def append_events(self, runtime_id: str, job_id: str, owner: str, events: list[Row], lease_seconds: int) -> Row: ...
    @abstractmethod
    def complete_job(self, runtime_id: str, job_id: str, owner: str, final_seq: int, text_sha256: str, result: Row) -> Row: ...
    @abstractmethod
    def fail_job(self, runtime_id: str, job_id: str, owner: str, code: str, message: str, retryable: bool) -> Row: ...
    @abstractmethod
    def ack_cancel(self, runtime_id: str, job_id: str, owner: str) -> Row: ...
    @abstractmethod
    def request_cancel(self, workspace_id: str, job_id: str) -> Row: ...
    @abstractmethod
    def get_job(self, job_id: str) -> Row | None: ...
    @abstractmethod
    def list_events(self, job_id: str, after_seq: int, limit: int) -> list[Row]: ...
    @abstractmethod
    def expire_jobs(self, runtime_id: str | None = None) -> None: ...

    # ---- telemetry
    @abstractmethod
    def ingest_telemetry(self, runtime_id: str, batch_id: str, run_id: str | None, gpu: list[Row], vllm: list[Row]) -> Row: ...
    @abstractmethod
    def query_gpu(self, project_id: str, runtime_id: str | None, since: datetime, until: datetime, limit: int) -> list[Row]: ...
    @abstractmethod
    def query_vllm(self, project_id: str, runtime_id: str | None, since: datetime, until: datetime, limit: int) -> list[Row]: ...

    # ---- runs / housekeeping
    @abstractmethod
    def reap_runs(self, stale_seconds: int = 90) -> int: ...
    @abstractmethod
    def list_runs(self, project_id: str, limit: int = 50) -> list[Row]: ...
    @abstractmethod
    def get_run(self, run_id: str) -> Row | None: ...
    @abstractmethod
    def prune(self, event_hours: int = 48, gpu_days: int = 14, vllm_days: int = 14) -> Row: ...

    def ready(self) -> None:
        """Readiness probe: raise StoreUnavailable if the backing database cannot serve a trivial read. In-memory/legacy stores have nothing to check."""
        return None

    @abstractmethod
    def audit(self, workspace_id: str | None, actor: str, action: str, target_type: str | None = None, target_id: str | None = None, meta: Row | None = None) -> None: ...


class StoreUnavailable(RuntimeError):
    """Database unreachable or returned an unexpected status. Routes map this to 503; messages never include row data."""
