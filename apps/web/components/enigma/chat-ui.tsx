/** Minimal, XSS-safe renderer: splits ``` fences into <pre><code> and renders everything as React text nodes (never HTML). */
export function RichText({ text }: { text: string }) {
  const parts = text.split(/```/);
  return (
    <>
      {parts.map((p, i) => i % 2 === 1
        ? <pre key={i} className="my-2 overflow-x-auto rounded-md bg-muted p-3 font-mono text-xs"><code>{p.replace(/^[a-zA-Z0-9_+-]*\n/, "")}</code></pre>
        : <span key={i} className="whitespace-pre-wrap break-words">{p}</span>)}
    </>
  );
}

export function MessageBubble({ role, children, footer, streaming, testId }: { role: "user" | "assistant" | "system"; children: React.ReactNode; footer?: React.ReactNode; streaming?: boolean; testId?: string }) {
  const user = role === "user";
  return (
    <div className={cn("flex gap-3", user && "flex-row-reverse")} data-testid={testId} data-role={role}>
      <span aria-hidden className={cn("mt-1 grid size-7 shrink-0 place-items-center rounded-full border", user ? "bg-primary text-primary-foreground" : "bg-card")}>{user ? <User className="size-4" /> : <Bot className="size-4" />}</span>
      <div className={cn("max-w-[85%] min-w-0 rounded-2xl px-4 py-2.5 text-sm leading-relaxed", user ? "bg-primary text-primary-foreground" : "border bg-card")}>
        <span className="sr-only">{user ? "You said:" : "Model replied:"}</span>
        {children}
        {streaming ? <span aria-hidden className="ml-0.5 inline-block h-4 w-1.5 translate-y-0.5 animate-pulse bg-current" /> : null}
        {footer ? <div className="mt-2 border-t border-border/50 pt-1.5 text-xs text-muted-foreground">{footer}</div> : null}
      </div>
    </div>
  );
}

/** Scroll container that follows new content only while the reader is at the bottom (so reading history is never yanked away). */
export function MessageScroller({ children, deps }: { children: React.ReactNode; deps: unknown[] }) {
  const ref = useRef<HTMLDivElement>(null);
  const [atBottom, setAtBottom] = useState(true);
  const near = (el: HTMLElement) => el.scrollHeight - el.scrollTop - el.clientHeight < 80;
  useEffect(() => {
    const el = ref.current;
    if (el && atBottom) el.scrollTop = el.scrollHeight;
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, deps);
  return (
    <div className="relative min-h-0 flex-1">
      <div ref={ref} onScroll={(e) => setAtBottom(near(e.currentTarget))} role="log" aria-live="polite" aria-relevant="additions text" aria-label="Conversation" tabIndex={0}
        className="flex h-full flex-col gap-4 overflow-y-auto p-4" data-testid="message-scroller">{children}</div>
      {!atBottom ? <Button size="icon-sm" variant="secondary" className="absolute right-4 bottom-3 shadow" aria-label="Jump to latest message" onClick={() => { const el = ref.current; if (el) { el.scrollTop = el.scrollHeight; setAtBottom(true); } }}><ArrowDown /></Button> : null}
    </div>
  );
}

export function PromptInput({ onSend, onCancel, running, disabled, disabledReason, maxChars = 16000 }: { onSend: (t: string) => Promise<boolean> | boolean; onCancel: () => void; running: boolean; disabled: boolean; disabledReason?: string; maxChars?: number }) {
  const [text, setText] = useState("");
  const submit = async () => {
    const t = text.trim();
    if (!t || disabled || running) return;
    if (await onSend(t)) setText("");
  };
  return (
    <div className="border-t p-3">
      <div className="flex items-end gap-2">
        <Textarea value={text} onChange={(e) => setText(e.target.value)} maxLength={maxChars} rows={2} placeholder={disabled ? disabledReason : "Ask the model something… (Enter to send, Shift+Enter for a new line)"} aria-label="Prompt" data-testid="prompt-input"
          className="max-h-40 min-h-[3rem] resize-none" disabled={disabled && !running}
          onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) { e.preventDefault(); void submit(); } }} />
        {running
          ? <Button variant="destructive" onClick={onCancel} data-testid="cancel-button"><Square aria-hidden />Stop</Button>
          : <Button onClick={() => void submit()} disabled={disabled || !text.trim()} data-testid="send-button"><Send aria-hidden />Send</Button>}
      </div>
      <div className="mt-1 flex justify-between text-xs text-muted-foreground"><span>{disabled && disabledReason ? disabledReason : "Replies are generated by the connected model, not by Enigma."}</span><span className="tabular">{text.length}/{maxChars}</span></div>
    </div>
  );
}

export function MeasuredLine({ m }: { m: Measured | undefined }) {
  if (!m) return null;
  return (
    <span className="tabular flex flex-wrap items-center gap-x-3 gap-y-1" data-testid="measured-line">
      {m.is_mock ? <MockBadge /> : null}
      <span>TTFT {fmt.ms(m.ttft_ms)}</span><span>total {fmt.ms(m.e2e_ms)}</span><span>{m.stream_chunks ?? "N/A"} chunks</span>
      {m.chunks_per_s != null ? <span>{m.chunks_per_s.toFixed(1)} chunks/s</span> : null}
    </span>
  );
}
