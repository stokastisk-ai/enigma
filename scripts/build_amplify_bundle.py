"""OFFLINE proof-of-concept: assemble the Next.js 16 standalone build into the Amplify Hosting *deployment specification* layout and check it.

    /usr/local/bin/python3.13 scripts/build_amplify_bundle.py [--build] [--serve-check] [--json]

NO AWS calls, NO AWS resources, NO GPU, no secrets. It only reshapes local build output under apps/web/.amplify-hosting (git-ignored).
Spec: https://docs.aws.amazon.com/amplify/latest/userguide/ssr-deployment-specification.html (inspected 2026-11-22).

What this proves : the output conforms to the documented layout/limits and the compute entry serves SSR on port 3000 locally.
What it CANNOT prove: that Amplify Hosting's managed compute runs Next.js 16 correctly (proxy.ts, cookies, Set-Cookie, HEAD/redirect behaviour,
                      response buffering, cold start). AWS documents managed SSR for Next.js 12-15 only, and lists Next.js streaming as UNSUPPORTED.
                      A conformant bundle is therefore NOT proof of support. Only an approved real deployment could show that.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import socket
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "apps" / "web"
DIST = ".next-standalone"
PKG = WEB / DIST / "standalone"
OUT = WEB / ".amplify-hosting"
MAX_COMPUTE_BYTES = 220 * 1024 * 1024  # documented uncompressed limit for compute/default
MAX_ROUTES = 25
ENTRY = "amplify-entry.js"
SKIP = shutil.ignore_patterns(".env*", "*.map", "*.tsbuildinfo", "*.pem", "*.key")

# Wrapper because the spec requires the HTTP server on port 3000, while Next's server.js reads PORT/HOSTNAME from the environment.
ENTRY_JS = """\
// Amplify Hosting compute entrypoint (generated by scripts/build_amplify_bundle.py). Spec: HTTP server on port 3000.
process.env.PORT = "3000";
process.env.HOSTNAME = "0.0.0.0";
process.env.NODE_ENV = "production";
require("./server.js");
"""


def build() -> None:
    env = {**os.environ, "ENIGMA_STANDALONE": "1", "ENIGMA_DIST_DIR": DIST}
    subprocess.run(["npx", "next", "build"], cwd=WEB, env=env, check=True, capture_output=True)


def assemble() -> dict:
    if not (PKG / "server.js").exists():
        sys.exit("standalone output missing: run with --build")
    # Containment: only ever delete/recreate the one fixed output directory directly under apps/web.
    if OUT.resolve().parent != WEB.resolve() or OUT.name != ".amplify-hosting":
        sys.exit("refusing to touch an unexpected output path")
    if OUT.is_symlink():
        sys.exit("refusing: output path is a symlink")
    shutil.rmtree(OUT, ignore_errors=True)
    compute, static = OUT / "compute" / "default", OUT / "static"
    # symlinks=True copies links AS links (never follows them out of the tree); validate() then fails the build if any exist.
    # .env* / source maps / tsbuildinfo are excluded at copy time so credentials and absolute-path metadata cannot enter the artifact.
    shutil.copytree(PKG, compute, symlinks=True, ignore=SKIP)
    # Next's standalone omits static assets and public/: the compute copy needs them for fallback; the static primitive serves them from the edge.
    shutil.copytree(WEB / DIST / "static", compute / DIST / "static", dirs_exist_ok=True, symlinks=True, ignore=SKIP)
    shutil.copytree(WEB / DIST / "static", static / "_next" / "static", dirs_exist_ok=True, symlinks=True, ignore=SKIP)
    if (WEB / "public").exists():
        shutil.copytree(WEB / "public", compute / "public", dirs_exist_ok=True, symlinks=True, ignore=SKIP)
        shutil.copytree(WEB / "public", static, dirs_exist_ok=True, symlinks=True, ignore=SKIP)
    (compute / ENTRY).write_text(ENTRY_JS)
    node_major = re.match(r"v(\d+)", subprocess.run(["node", "--version"], capture_output=True, text=True, check=True).stdout).group(1)
    manifest = {
        "version": 1,
        "framework": {"name": "next", "version": json.loads((WEB / "package.json").read_text())["dependencies"]["next"]},
        # no imageSettings: images are unoptimized (no next/image), so there is no ImageOptimization route
        "computeResources": [{"name": "default", "runtime": f"nodejs{node_major}.x", "entrypoint": ENTRY}],
        "routes": [
            {"path": "/_next/static/*", "target": {"kind": "Static", "cacheControl": "public, max-age=31536000, immutable"}},
            {"path": "/*.*", "target": {"kind": "Static"}, "fallback": {"kind": "Compute", "src": "default"}},
            {"path": "/*", "target": {"kind": "Compute", "src": "default"}},
        ],
    }
    (OUT / "deploy-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def validate(manifest: dict) -> list[tuple[str, bool, str]]:
    res: list[tuple[str, bool, str]] = []
    add = lambda n, ok, d="": res.append((n, bool(ok), d))  # noqa: E731
    compute = OUT / "compute" / "default"
    size = sum(p.stat().st_size for p in compute.rglob("*") if p.is_file())
    add("manifest version == 1", manifest["version"] == 1)
    add("framework metadata present", bool(manifest.get("framework", {}).get("name")))
    routes = manifest["routes"]
    add(f"routes <= {MAX_ROUTES}", len(routes) <= MAX_ROUTES, str(len(routes)))
    add("catch-all /* route present", any(r["path"] == "/*" for r in routes))
    add("every route path starts with / and uses allowed chars", all(re.fullmatch(r"/[A-Za-z0-9 _\-.*$/~\"'@:+]*", r["path"]) and len(r["path"]) <= 255 for r in routes))
    add("Compute route has a compute resource", all(any(c["name"] == r["target"].get("src") for c in manifest["computeResources"]) for r in routes if r["target"]["kind"] == "Compute"))
    add("static dir exists (Static route used)", (OUT / "static").is_dir())
    add("compute/default has the entry file", (compute / ENTRY).is_file())
    add("runtime is nodejs20.x/22.x/24.x", manifest["computeResources"][0]["runtime"] in {"nodejs20.x", "nodejs22.x", "nodejs24.x"}, manifest["computeResources"][0]["runtime"])
    add("compute/default <= 220 MB uncompressed", size <= MAX_COMPUTE_BYTES, f"{size / 1e6:.1f} MB")
    add("no .env files in the bundle", not list(OUT.rglob(".env*")))
    add("no symlinks anywhere in the bundle (nothing can point outside it)", not [p for p in OUT.rglob("*") if p.is_symlink()])
    add("entry resolves inside compute/default", (compute / ENTRY).resolve().is_relative_to(compute.resolve()))
    add("no source maps / key material", not [p for p in OUT.rglob("*") if p.suffix in {".map", ".pem", ".key"}])
    leak = [p.name for p in (OUT / "static").rglob("*") if p.is_file() and p.stat().st_size < 5_000_000 and any(h in p.read_bytes() for h in (str(ROOT).encode(), str(Path.home()).encode()))]
    add("PUBLIC static tree contains no build-host paths or usernames", not leak, ",".join(leak[:3]))
    add("every compute-referenced static route dir exists", all((OUT / "static" / "_next" / "static").is_dir() for r in routes if r["path"].startswith("/_next/static")))
    add("no native binaries (.node/.so)", not [p for p in OUT.rglob("*") if p.suffix in {".node", ".so"}])
    return res


def serve_check() -> list[tuple[str, bool, str]]:
    """Run the compute entry exactly as the spec says (`node <entry>` inside compute/default) and hit it."""
    with socket.socket() as s:
        if s.connect_ex(("127.0.0.1", 3000)) == 0:
            return [("port 3000 is free for the local check", False, "something already listens on 3000; not touching it")]
    env = {k: v for k, v in os.environ.items() if not k.startswith(("AWS_", "CLERK", "COGNITO"))}
    env["ENIGMA_AUTH_PROVIDER"] = "none"
    p = subprocess.Popen(["node", ENTRY], cwd=OUT / "compute" / "default", env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    out: list[tuple[str, bool, str]] = []
    try:
        for _ in range(60):
            try:
                urllib.request.urlopen("http://127.0.0.1:3000/", timeout=1).read()
                break
            except Exception:
                time.sleep(0.25)
        r = urllib.request.urlopen("http://127.0.0.1:3000/", timeout=5)
        out.append(("entry listens on :3000 and serves SSR /", r.status == 200, str(r.status)))
        css = re.search(r"/_next/static/[^\"']+\.css", r.read().decode())
        if css:
            a = urllib.request.urlopen("http://127.0.0.1:3000" + css.group(0), timeout=5)
            out.append(("compute fallback serves a hashed static asset", a.status == 200, css.group(0)[:60]))
            out.append(("that asset also exists in the static primitive dir", (OUT / "static" / css.group(0).lstrip("/")).is_file(), ""))
    except Exception as e:  # noqa: BLE001
        out.append(("local serve check", False, type(e).__name__))
    finally:
        p.terminate()
        p.wait(timeout=10)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--serve-check", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    if a.build or not (PKG / "server.js").exists():
        build()
    manifest = assemble()
    results = validate(manifest) + (serve_check() if a.serve_check else [])
    if a.json:
        print(json.dumps([{"check": n, "ok": ok, "detail": d} for n, ok, d in results], indent=2))
    else:
        for n, ok, d in results:
            print(f"  [{'PASS' if ok else 'FAIL'}] {n}" + (f"  ({d})" if d else ""))
        print("NOT PROVEN: Amplify managed compute running Next.js 16 (docs cover 12-15; streaming unsupported). No AWS call was made.")
    return 0 if all(ok for _, ok, _ in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
