"""SYNTHETIC test doubles. Everything here is fake and is registered with ``is_mock=true`` so the API and UI label it as example data.

MockLlm streams a deterministic canned reply word by word; MockGpu/MockVllm produce smooth synthetic curves. None of this is a
measurement of any GPU, and the server refuses a mock connector on a credential issued for a real runtime (mock_mismatch)."""
from __future__ import annotations

import hashlib
import math
import time
from datetime import datetime, timezone
from typing import Iterator

MOCK_BANNER = "[MOCK MODEL - synthetic output, not generated by a GPU] "


class MockLlm:
    def __init__(self, token_delay_s: float = 0.02, first_token_delay_s: float = 0.05, sleep=time.sleep, vllm: "MockVllm | None" = None):
        self.token_delay_s, self.first_token_delay_s, self.sleep, self.vllm = token_delay_s, first_token_delay_s, sleep, vllm
        self.calls = 0

    def stream(self, messages, *, max_tokens, temperature, model) -> Iterator[str]:
        self.calls += 1
        last = messages[-1]["content"] if messages else ""
        digest = hashlib.sha256(last.encode()).hexdigest()[:8]
        words = (MOCK_BANNER + f"echo({digest}) " + " ".join(last.split()[:40])).split(" ")[:max_tokens]
        t0 = time.monotonic()
        if self.vllm:
            self.vllm.running += 1
        n = 0
        try:
            self.sleep(self.first_token_delay_s)
            ttft = time.monotonic() - t0
            for w in words:
                yield w + " "
                n += 1
                self.sleep(self.token_delay_s)
        finally:                                         # runs on normal end AND on generator.close() (cancel)
            if self.vllm:
                self.vllm.running -= 1
                self.vllm.record_request(sum(len(m["content"].split()) for m in messages), n, ttft if n else 0.0, time.monotonic() - t0)


class MockGpu:
    """Looks like NvmlSampler (inventory/sample/close) with deterministic synthetic values for 2 GPUs. Optional fields can be disabled."""

    def __init__(self, n: int = 2, with_pcie: bool = False, busy=lambda: 0.0):
        self.n, self.with_pcie, self.busy, self._t0 = n, with_pcie, busy, time.monotonic()

    def inventory(self):
        return [{"index": i, "uuid": f"GPU-MOCK-{i}", "name": "MOCK NVIDIA T4 (synthetic)", "memory_total_mib": 15360.0, "driver": "mock"} for i in range(self.n)]

    def sample(self, now: datetime | None = None):
        ts = (now or datetime.now(timezone.utc)).isoformat()
        t = time.monotonic() - self._t0
        rows = []
        for i in range(self.n):
            util = min(100.0, max(0.0, 8 + 6 * math.sin(t / 5 + i) + 80 * self.busy()))
            rows.append({"captured_at": ts, "gpu_index": i, "gpu_uuid": f"GPU-MOCK-{i}", "util_gpu_pct": round(util, 1), "util_mem_pct": round(util / 2, 1),
                         "mem_used_mib": 1200.0 + 40 * i + 5 * math.sin(t), "mem_total_mib": 15360.0, "temp_c": 38.0 + 0.1 * util, "power_w": 25.0 + 0.4 * util,
                         "power_limit_w": 70.0, "sm_clock_mhz": 585.0 + 8 * util, "mem_clock_mhz": 5001.0,
                         "pcie_rx_kib_s": 1000.0 * (1 + math.sin(t)) if self.with_pcie else None, "pcie_tx_kib_s": 500.0 if self.with_pcie else None})
        return rows

    def supported_counters(self):
        return {"util": True, "mem": True, "temp": True, "power": True, "pcie_rx": self.with_pcie, "pcie_tx": self.with_pcie}

    def close(self):
        pass


class MockVllm:
    """Synthetic cumulative vLLM-style samples. ``record_request`` is called by the mock LLM path so counters move with fake traffic."""
    LE = [0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5]

    def __init__(self):
        self.epoch = 0
        self.prompt = self.gen = 0.0
        self.counts = {"ttft": [0.0] * (len(self.LE) + 1), "e2e": [0.0] * (len(self.LE) + 1), "itl": [0.0] * (len(self.LE) + 1)}
        self.sums = {"ttft": 0.0, "e2e": 0.0, "itl": 0.0}
        self.running = 0
        self.last_error = None

    def record_request(self, prompt_tokens: int, gen_tokens: int, ttft_s: float, e2e_s: float):
        self.prompt += prompt_tokens
        self.gen += gen_tokens
        for name, v in (("ttft", ttft_s), ("e2e", e2e_s), ("itl", e2e_s / max(gen_tokens, 1))):
            self.sums[name] += v
            for i, le in enumerate(self.LE + [float("inf")]):
                if v <= le:
                    self.counts[name][i] += 1

    def _hist(self, name):
        # counts[] is already cumulative: record_request increments every bucket whose bound is >= the observation
        cum = list(self.counts[name])
        return {"le": self.LE, "cum": cum, "sum": self.sums[name], "count": cum[-1]}

    def sample(self, now: datetime | None = None):
        return {"captured_at": (now or datetime.now(timezone.utc)).isoformat(), "counter_epoch": self.epoch, "num_requests_running": float(self.running),
                "num_requests_waiting": 0.0, "kv_cache_usage_perc": min(1.0, self.gen / 20000.0), "prompt_tokens_total": self.prompt,
                "generation_tokens_total": self.gen, "preemptions_total": 0.0, "request_success": {"stop": float(self.counts["e2e"][-1])},
                "ttft_hist": self._hist("ttft"), "e2e_hist": self._hist("e2e"), "itl_hist": self._hist("itl")}
